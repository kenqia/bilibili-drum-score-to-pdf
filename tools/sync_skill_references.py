#!/usr/bin/env python3
"""Generate portable Skill protocols from repository documentation."""
import argparse
import posixpath
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SKILL = Path('skills/bilibili-drum-score-to-pdf')
PROTOCOLS = (
    'stage-recovery-layout', 'reconstruction-entry', 'reconstruction-workflow',
    'reconstruction-local', 'reconstruction-navigation', 'automatic-source-checks',
    'midi-conversion', 'reconstruction-implementation-status',
)
SOURCES = {f'docs/agents/{name}.md': f'{name}.md' for name in PROTOCOLS}
REPOSITORY_URL = 'https://github.com/kenqia/bilibili-drum-score-to-pdf/blob/main/'


def render(source, text):
    def link(match):
        label, target = match.groups()
        if '://' in target or target.startswith('#'):
            return match.group(0)
        path, separator, anchor = target.partition('#')
        resolved = posixpath.normpath(posixpath.join(posixpath.dirname(source), path))
        destination = SOURCES.get(resolved, REPOSITORY_URL + resolved)
        return f'[{label}]({destination}{separator}{anchor})'
    text = re.sub(r'\[([^\]]+)\]\(([^)]+)\)', link, text)
    text = text.replace('skills/bilibili-drum-score-to-pdf/scripts/', 'scripts/')
    return ('<!-- Generated by tools/sync_skill_references.py; edit ' + source + '. -->\n'
            '\n以下命令相对 Skill 根目录执行。历史证据链接仅供查阅，不是运行依赖。\n\n' + text)


def sync(root=ROOT, check=False):
    stale = []
    for source, name in SOURCES.items():
        destination = root / SKILL / 'references' / name
        expected = render(source, (root / source).read_text())
        if not destination.is_file() or destination.read_text() != expected:
            stale.append(str(destination.relative_to(root)))
            if not check:
                destination.parent.mkdir(parents=True, exist_ok=True)
                destination.write_text(expected)
    license_file = root / SKILL / 'LICENSE'
    expected_license = (root / 'LICENSE').read_text()
    if not license_file.is_file() or license_file.read_text() != expected_license:
        stale.append(str(license_file.relative_to(root)))
        if not check:
            license_file.write_text(expected_license)
    return stale


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    stale = sync(check=args.check)
    if args.check and stale:
        parser.exit(1, 'Skill references are stale: ' + ', '.join(stale) + '\n')
    print('Skill references match repository protocols.' if args.check else 'Skill references generated.')


if __name__ == '__main__':
    main()
